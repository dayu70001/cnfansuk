test("WhatsApp navigation remains immediate while an authorized click event uses a keepalive request", () => {
  assert.match(checkoutSource, /recordWhatsAppOrderClick\(order\)/);
  assert.match(checkoutSource, /href=\{whatsappHref\}[\s\S]*?onClick=\{onWhatsAppClick\}/);
  assert.match(checkoutSource, /\/api\/orders\/\$\{encodeURIComponent\(order\.orderNumber\)\}\/whatsapp-clicked/);
  assert.match(checkoutSource, /"X-Order-Access-Token": order\.orderAccessToken/);
  assert.match(checkoutSource, /keepalive:\s*true/);
});
